#[test]
fn generator_contract_eight_cases_validate_each_producer_independently() {
    let reference = format!("{ORCA}G1 X1\n");
    let actual = format!("{ARES}G1 X1\n");
    compare(reference.as_bytes(), actual.as_bytes()).unwrap();
    for (header, expected_name) in [(ORCA, "OrcaSlicer"), (ARES, "Ares")] {
        let invalid = [
            "G1 X1\n".as_bytes().to_vec(),
            format!("{header}{header}G1 X1\n").into_bytes(),
            format!("{}G1 X1\n", if header == ORCA { ARES } else { ORCA }).into_bytes(),
            format!("{}G1 X1\n", header.replace("2.4.2", "2.4.3")).into_bytes(),
            format!("{}G1 X1\n", header.replace(" at ", " ")).into_bytes(),
            format!("prefix {header}G1 X1\n").into_bytes(),
            [header.as_bytes(), &[0xff]].concat(),
        ];
        for bytes in invalid {
            let error = if header == ORCA {
                assert_ne!(bytes, reference.as_bytes());
                compare(&bytes, actual.as_bytes())
            } else {
                assert_ne!(bytes, actual.as_bytes());
                compare(reference.as_bytes(), &bytes)
            }
            .unwrap_err();
            assert!(
                error.contains(expected_name) || error.contains("utf-8"),
                "{error}"
            );
        }
    }
}

#[test]
fn do_export_preserves_six_stream_boundaries() {
    let reference = format!("{ORCA}G1 X1 Y2\n");
    let baseline = format!("{ARES}G1 X1 Y2\n");
    for body in [
        "G1  X1 Y2\n",
        "G1 X1 Y2\r\n",
        "G1 X1 Y2",
        "G1 X1 Y2\n\n",
        "G1 X1 Y2\nx",
        "G1 X1",
    ] {
        reject(
            &reference,
            &baseline,
            &format!("{ARES}{body}"),
            "stream boundary",
        );
    }
}
