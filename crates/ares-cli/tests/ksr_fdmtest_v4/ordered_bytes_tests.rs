//! Comparator contracts, not Ares slicing passes. Real records come from the
//! committed classic stream; absent arc/multi-object streams below are synthetic.
//! Orca 8500fcd: GCode::do_export (config/statistics/object boundaries),
//! GCodeWriter::{travel_to_xy,travel_to_z,extrude_to_xy,extrude_arc_to_xy,
//! set_acceleration,set_temperature,set_fan,retract}, GCodeProcessor::run_post_process.
use super::compare_ordered_bytes_generator_only as compare;

const ORCA: &str = "; generated by OrcaSlicer 2.4.2 on 2026-09-08 at 04:26:03\n";
const ARES: &str = "; generated by Ares 2.4.2 on 2030-12-31 at 23:59:58\n";
const CLASSIC: &str = include_str!("../../../../tests/parity/replay/ender3-classic.orca.gcode");

fn reject(reference: &str, baseline: &str, changed: &str, label: &str) {
    assert_ne!(baseline, changed, "mutation missed: {label}");
    let error = compare(reference.as_bytes(), changed.as_bytes()).unwrap_err();
    assert!(
        error.contains("first difference at byte"),
        "{label}: {error}"
    );
}

fn mutations(reference: &str, first: &str, second: &str, changed: &str, label: &str) {
    // Header substitution constructs only a comparator input, never an Orca replay.
    assert_eq!(reference.matches(ORCA).count(), 1);
    let baseline = reference.replacen(ORCA, ARES, 1);
    compare(reference.as_bytes(), baseline.as_bytes()).unwrap();
    let lines: Vec<_> = baseline.split_inclusive('\n').collect();
    let i = lines.iter().position(|line| *line == first).unwrap();
    let j = lines.iter().position(|line| *line == second).unwrap();
    assert!(i < j, "ordered distinct anchors: {label}");
    assert_ne!(first, second);
    assert_ne!(first, changed);
    let mut replacement = lines.clone();
    replacement[i] = changed;
    reject(
        reference,
        &baseline,
        &replacement.concat(),
        &format!("{label}/change"),
    );
    let mut deletion = lines.clone();
    deletion.remove(i);
    assert_eq!(deletion.len() + 1, lines.len());
    reject(
        reference,
        &baseline,
        &deletion.concat(),
        &format!("{label}/delete"),
    );
    let mut reordered = lines;
    reordered.swap(i, j);
    assert_eq!((reordered[i], reordered[j]), (second, first));
    reject(
        reference,
        &baseline,
        &reordered.concat(),
        &format!("{label}/reorder"),
    );
}

