fn fixture_path(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/ksr_fdmtest_v4")
        .join(name)
}

fn project() -> Vec<u8> {
    fs::read(fixture_path("ksr_fdmtest_v4.project.3mf")).unwrap()
}

fn reference() -> Vec<u8> {
    fs::read(fixture_path("ksr_fdmtest_v4.gcode")).unwrap()
}

fn sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn count_bytes(haystack: &[u8], needle: &[u8]) -> usize {
    haystack
        .windows(needle.len())
        .filter(|window| *window == needle)
        .count()
}

fn compare_actual(actual: &[u8]) {
    golden::compare_ordered_bytes_generator_only(&reference(), actual)
        .unwrap_or_else(|error| panic!("{error}"));
}

fn local_now_to_second() -> DateTime {
    let now = jiff::Zoned::now().datetime();
    DateTime::new(
        now.year(),
        now.month(),
        now.day(),
        now.hour(),
        now.minute(),
        now.second(),
        0,
    )
    .unwrap()
}

fn generated_at(bytes: &[u8]) -> DateTime {
    let prefix = "; generated by Ares 2.4.2 on ";
    let line = std::str::from_utf8(bytes)
        .unwrap()
        .lines()
        .find_map(|line| line.strip_prefix(prefix))
        .unwrap();
    line.replace(" at ", " ").parse().unwrap()
}
